"""The same-eye fit and compose for Vulkan (PerEyeDlss_Vk), compiled to SPIR-V from THE SAME SOURCE as D3D12.

Reads kFitShader and kComposeShader out of OptiScaler/inputs/PerEyeFitShader_Dx12.h (each is several adjacent raw
literals: MSVC caps one at 16 KB), compiles each with the fork's own dxc (-spirv -D VK_MODE, as
shaders/shader_tools/build_precompiled_shader_vk.bat), and writes OptiScaler/inputs/PerEyeFitShader_Vk.h with the two
SPIR-V blobs. Run after every change to the shaders; vk_fit_test checks the header is newer than the source.
Exit code non-zero on any failure (a build must stop on it).
"""
import os
import re
import subprocess
import sys
import tempfile

here = os.path.dirname(os.path.abspath(__file__))
fork = os.path.normpath(os.path.join(here, '..', '..', '..'))
src = os.path.join(fork, 'OptiScaler', 'inputs', 'PerEyeFitShader_Dx12.h')
dst = os.path.join(fork, 'OptiScaler', 'inputs', 'PerEyeFitShader_Vk.h')
dxc = os.path.join(fork, 'OptiScaler', 'shaders', 'shader_tools', 'dxc.exe')


def extract(text, name):
    start = text.index('constexpr char %s[] =' % name)
    end = text.index(';', text.index('R"(', start))
    # the ';' found may sit inside a literal: walk literal by literal instead
    pos = text.index('=', start) + 1
    parts = []
    while True:
        m = re.compile(r'\s*(?://[^\n]*\n\s*)*R"\(').match(text, pos)
        if not m:
            break
        body_start = m.end()
        body_end = text.index(')"', body_start)
        parts.append(text[body_start:body_end])
        pos = body_end + 2
    rest = text[pos:pos + 20].lstrip()
    if not rest.startswith(';') or not parts:
        raise SystemExit('could not read %s (%d literals, then %r)' % (name, len(parts), rest[:10]))
    return ''.join(parts)


text = open(src, encoding='utf-8').read().replace('\r\n', '\n')
out = ['#pragma once', '',
       '// GENERATED by tools/xr_observer/test/vk_fit_shaders.py from PerEyeFitShader_Dx12.h (the same source, VK_MODE,',
       '// the fork\'s dxc -spirv). Do not edit; run the script after every change to the shaders.', '']
for name, var in (('kFitShader', 'kFitShaderSpv'), ('kComposeShader', 'kComposeShaderSpv')):
    hlsl = extract(text, name)
    with tempfile.TemporaryDirectory() as tmp:
        hp = os.path.join(tmp, name + '.hlsl')
        sp = os.path.join(tmp, name + '.spv')
        open(hp, 'w', encoding='utf-8').write(hlsl)
        r = subprocess.run([dxc, '-spirv', '-T', 'cs_6_0', '-E', 'CSMain', '-O3', '-Qstrip_debug', '-D', 'VK_MODE',
                            hp, '-Fo', sp], capture_output=True, text=True)
        if r.returncode != 0:
            print(r.stdout)
            print(r.stderr)
            raise SystemExit('dxc FAILED on %s' % name)
        blob = open(sp, 'rb').read()
    assert len(blob) % 4 == 0 and blob[:4] == b'\x03\x02\x23\x07', 'not SPIR-V'
    words = [int.from_bytes(blob[i:i + 4], 'little') for i in range(0, len(blob), 4)]
    out.append('inline constexpr uint32_t %s[] = {' % var)
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    out.append('};')
    out.append('')
    print('%s: %d bytes of SPIR-V' % (name, len(blob)))
open(dst, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('wrote', dst)
